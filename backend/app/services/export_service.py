import csv
import io
import json
from typing import List
from backend.app.models.record import CollectedRecord
from backend.app.models.research import ResearchProject

def export_records_to_csv(records: List[CollectedRecord]) -> str:
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "ID", "Title", "Source", "Type", "Category", "URL", "Author", "Published", "Tags", "Quality Score"
    ])
    for r in records:
        writer.writerow([
            r.id,
            r.title,
            r.source_name,
            r.source_type,
            r.category,
            r.original_url,
            r.author or "",
            r.published_at.isoformat() if r.published_at else "",
            r.tags or "",
            r.quality_score
        ])
    return output.getvalue()

def export_records_to_json(records: List[CollectedRecord]) -> str:
    data = []
    for r in records:
        data.append({
            "id": r.id,
            "title": r.title,
            "description": r.description,
            "url": r.original_url,
            "source_name": r.source_name,
            "source_type": r.source_type,
            "category": r.category,
            "author": r.author,
            "published_at": r.published_at.isoformat() if r.published_at else None,
            "tags": [t.strip() for t in r.tags.split(",") if t.strip()] if r.tags else [],
            "quality_score": r.quality_score
        })
    return json.dumps(data, indent=2, ensure_ascii=False)

def export_project_to_markdown(project: ResearchProject) -> str:
    lines = [
        f"# Research Dossier: {project.title}",
        f"**Generated by Scoutboard** | {project.updated_at.strftime('%Y-%m-%d %H:%M UTC')}",
        "",
        "## Research Question",
        project.research_question or "No specific research question recorded.",
        "",
        "## Project Overview",
        project.description or "No description provided.",
        "",
        f"**Tags:** `{project.tags or 'None'}`",
        "",
        "---",
        "## Research Notes",
    ]

    if not project.notes:
        lines.append("_No notes written yet._\n")
    else:
        for note in project.notes:
            lines.extend([
                f"### {note.title}",
                f"_Last updated: {note.updated_at.strftime('%Y-%m-%d')}_",
                "",
                note.content_markdown,
                "",
            ])

    lines.extend([
        "---",
        "## Evidence & Citations",
    ])

    if not project.evidence:
        lines.append("_No citations attached yet._\n")
    else:
        for ev in project.evidence:
            rec = ev.record
            if rec:
                lines.extend([
                    f"- **[{rec.title}]({rec.original_url})**",
                    f"  - Source: `{rec.source_name or rec.source_type}` | Quality: `{rec.quality_score}`",
                    f"  - Notes: {ev.notes or 'No specific note'}",
                    ""
                ])

    return "\n".join(lines)
